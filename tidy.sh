#!/usr/bin/env bash
# Наведение порядка в student-cpp-portfolio по правилам из rules.md
# Запуск (Git Bash, из корня репозитория):  bash tidy.sh
# Все переименования делаются через git mv, поэтому история файлов сохраняется.

set -u
if [ ! -d .git ] || [ ! -f rules.md ]; then
  echo "Запусти скрипт из корня репозитория (там, где лежат .git и rules.md)."
  exit 1
fi
git config core.quotepath false

CPP="МДК.01.05 Основы программирования на языке С++"
OOP="МДК.01.06 Объектно-ориентированное программирование с использованием языка C++"

mvg() {  # mvg <откуда> <куда>
  if [ -e "$1" ] && [ ! -e "$2" ]; then
    mkdir -p "$(dirname "$2")"
    git mv "$1" "$2" && echo "  $1  ->  $2"
  fi
}

echo "== 1. Удаляю автора из SQL-файлов =="
find . -path ./.git -prune -o -name '*.sql' -print0 |
  xargs -0 -r sed -i '/^-- .*Мингазов Александр Рашидович/d'
grep -rIn --exclude-dir=.git --include='*.sql' "Мингазов" . || echo "  в .sql больше не упоминается"

echo "== 2. МДК.01.05: имена папок по rules.md =="
mvg "$CPP/Домашние_работы"    "$CPP/Домашние задания"
mvg "$CPP/Контрольные_работы" "$CPP/Контрольные работы"
for d in "$CPP/Домашние задания"/*/; do
  n=$(basename "$d")
  case "$n" in ДЗ_*) ;; *) mvg "$CPP/Домашние задания/$n" "$CPP/Домашние задания/ДЗ_$n" ;; esac
done
for d in "$CPP/Контрольные работы"/*/; do
  n=$(basename "$d")
  case "$n" in КОНТРОЛЬ_*) ;; *) mvg "$CPP/Контрольные работы/$n" "$CPP/Контрольные работы/КОНТРОЛЬ_${n##*_}" ;; esac
done

echo "== 3. МДК.01.06: имена папок по rules.md =="
mvg "$OOP/Домашние_работы"    "$OOP/Домашние задания"
mvg "$OOP/Контрольные_работы" "$OOP/Контрольные работы"
for d in "$OOP/Домашние задания"/*/; do
  n=$(basename "$d")
  case "$n" in
    ДЗ_*) ;;
    *) new=$(printf '%s' "$n" | tr -s ' ' | sed 's/\. /_/; s/ /_/g')
       mvg "$OOP/Домашние задания/$n" "$OOP/Домашние задания/ДЗ_$new" ;;
  esac
done
mvg "$OOP/Контрольные работы/practice_1.cpp" "$OOP/Контрольные работы/КОНТРОЛЬ_1/solution.cpp"
mvg "$OOP/Контрольные работы/practice_2.cpp" "$OOP/Контрольные работы/КОНТРОЛЬ_2/solution.cpp"

echo "== 4. Недостающие папки по rules.md (с .gitkeep) =="
ensure() {
  if [ ! -d "$1" ]; then
    mkdir -p "$1" && touch "$1/.gitkeep" && echo "  + $1"
  fi
}
for m in "МДК.01.01 Разработка программных модулей" \
         "МДК.01.02 Поддержка и тестирование программных модулей" \
         "$CPP" "$OOP"; do
  for s in "Конспекты" "Домашние задания" "Лабораторные и Практические работы" "Проекты" "Контрольные работы"; do
    ensure "$m/$s"
  done
done
for m in "МДК.01.03 Разработка мобильных приложений" \
         "МДК.01.07 Объектно-ориентированное проектирование.Язык UML и паттерны проектирования"; do
  for s in "Домашние задания" "Самостоятельные работы" "Работы на парах"; do
    ensure "$m/$s"
  done
done
for m in "МДК.01.08 Платформа Microsoft .NET и язык программирования C#" \
         "МДК.01.09 Основы разработки приложений с использованием Windows Forms и WPF"; do
  for s in "Домашние задания" "Контрольные работы" "Работы на парах"; do
    ensure "$m/$s"
  done
done

echo "== 5. Убираю лишние .gitkeep там, где уже есть файлы =="
find . -name .gitkeep -not -path './.git/*' | while read -r f; do
  d=$(dirname "$f")
  if [ "$(ls -A "$d" | wc -l)" -gt 1 ]; then
    git rm -q -f "$f" 2>/dev/null || rm -f "$f"
    echo "  - $f"
  fi
done

echo "== 6. README.md и rules.md =="
cat > README.md <<'EOF'
